//! # gui-ir —— 中间表示
//!
//! **零依赖。** 这个 crate 只定义数据结构，不含任何逻辑、不含任何第三方依赖。
//! 所有其它 crate 都可以依赖它，它不依赖任何人。
//!
//! ## 它是什么
//!
//! 「HTML/CSS/JS 源语言」经解析后的统一表示。三个后端（样式匹配、布局、绘制）
//! 和两个执行路径（开发期解释、发布期 AOT）**都从 IR 出发**，不各自解析一遍。
//!
//! ## 为什么不直接用 DOM
//!
//! 浏览器里 DOM 同时是「解析结果」和「运行时状态」—— 节点上有 style、有 layout
//! 结果、有事件监听。我们把这两件事拆开：
//!
//! - **IR 的节点树** = 静态模板。标签、属性、children。没有计算样式、没有几何。
//! - **gui-core 的 dom** = 运行时活树。有计算样式、有布局盒、有事件绑定、有可变状态。
//!
//! 拆开的好处：模板可以被序列化（编译期产物）、可以被对比（一致性测试）、
//! 可以被代码生成器遍历（生成建树代码），而运行时状态不会污染它。
//!
//! ## 三部分
//!
//! ```text
//!   NodeTree      结构模板（HTML 解析产物）
//!   StyleSheet    样式表（CSS 解析产物：规则 + 变量 + 主题）
//!   HostBindings  宿主 API 绑定（JS 与 Rust 之间的接口面）
//! ```
//!
//! 详见 [`docs/gui-source-language.md`](../../docs/gui-source-language.md)。

