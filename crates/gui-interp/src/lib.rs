//! # gui-interp —— 解释执行器（开发期）
//!
//! 解释执行 IR：把节点模板、样式表、逻辑**跑**起来，不生成代码。
//!
//! ## 它解决什么
//!
//! 改了 JS 想立刻看到效果，等 cargo 全量编译是几十秒起。这里是
//! **开发期专用**：解释执行，改完刷新就跑。
//!
//! ## 它和 AOT 的一致性
//!
//! 两条路径必须产出**同样的画面**。这是整个项目最关键的测试设施：
//! 同一批 HTML/CSS/JS 输入，解释执行的结果与 AOT 产物的结果逐像素相同。
//!
//! 详见 [`docs/gui-source-language.md`](../../docs/gui-source-language.md)。

